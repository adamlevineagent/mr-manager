"""Headless account: one `codex app-server` under a CODEX_HOME, owned by the daemon.

Workers share sign-in but use isolated homes with opt-in account defaults. MCP servers and
notify hooks are switched off, approvals are off with full access, and each lane gets its own
environment (ports, shared folders) through Codex's shell environment policy.
"""
import hashlib
import json
import os
import re
import shutil
import tempfile
import threading
import time
from pathlib import Path

from .appserver import AppServer, RpcError


_home_lock = threading.RLock()


def _sync_auth(account_home, home):
    """Copy the newest login in either direction, including after an atomic replacement.

    Codex currently truncates auth.json in place (login/src/auth/storage.rs); skip incomplete
    writes and retry on the next call. Never include credential contents in errors or logs.
    """
    account, worker = Path(account_home) / "auth.json", Path(home) / "auth.json"
    with _home_lock:
        a = account.stat() if account.exists() else None
        w = worker.stat() if worker.exists() else None
        if a and (not w or a.st_mtime_ns > w.st_mtime_ns):
            source, target, before = account, worker, a
        elif w and (not a or w.st_mtime_ns > a.st_mtime_ns):
            source, target, before = worker, account, w
        else:
            return
        target.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".auth-", dir=target.parent)
        os.close(fd)
        try:
            shutil.copy2(source, tmp)
            try:
                if not isinstance(json.loads(Path(tmp).read_text(encoding="utf-8")), dict):
                    return
            except (ValueError, UnicodeError):
                return
            after = source.stat()
            if (before.st_mtime_ns, before.st_size) != (after.st_mtime_ns, after.st_size):
                return
            # Don't overwrite a refresh that arrived while the copy was being prepared.
            if target.exists() and target.stat().st_mtime_ns >= before.st_mtime_ns:
                return
            os.replace(tmp, target)
        except (FileNotFoundError, PermissionError):
            pass   # a concurrent writer/replacement may briefly make the file unavailable
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)


def _remove_inherited(path):
    if path.is_symlink():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


def _inherit_names(inherit):
    if isinstance(inherit, str):
        raise ValueError("worker_inherit must be a list of top-level names")
    names = set(inherit)
    for name in names:
        if not isinstance(name, str) or name in ("", ".", "..") or "/" in name or "\\" in name \
                or Path(name).is_absolute() or ":" in name or name.startswith(".mr-manager-"):
            raise ValueError("worker_inherit must contain top-level names only")
    names.discard("auth.json")
    return names


def worker_home(account_home, root, inherit=()):
    """A stable per-account CODEX_HOME: shared login, opt-in account defaults.

    Inheritance is a list of top-level names, copied from the account on refresh. Session and
    other state generated by workers stays here between calls. Revoked inheritance is removed.
    """
    account = Path(account_home).expanduser().resolve()
    names = _inherit_names(inherit)
    key = hashlib.sha256(os.path.normcase(str(account)).encode()).hexdigest()[:20]
    home = Path(root).expanduser().resolve() / key
    with _home_lock:
        home.mkdir(parents=True, exist_ok=True)
        _sync_auth(account, home)
        manifest = home / ".mr-manager-inherit.json"
        previous = _inherit_names(json.loads(manifest.read_text(encoding="utf-8"))) if manifest.exists() else set()
        for name in previous - names:
            _remove_inherited(home / name)
        for name in sorted(names):
            source, target = account / name, home / name
            if not source.exists():
                _remove_inherited(target)
            else:
                if target.exists() and source.is_dir() != target.is_dir():
                    _remove_inherited(target)
                if source.is_dir():
                    shutil.copytree(source, target, dirs_exist_ok=True)
                else:
                    shutil.copy2(source, target)
        manifest.write_text(json.dumps(sorted(names)), encoding="utf-8")
    return str(home)


def _text(t):
    return {"type": "text", "text": t, "text_elements": []}


def _mcp_servers(home):
    try:
        cfg = (Path(home) / "config.toml").read_text(encoding="utf-8")
    except OSError:
        return []
    return sorted(set(re.findall(r"^\[mcp_servers\.([A-Za-z0-9_-]+)\]", cfg, re.M)))


class Headless:
    kind = "headless"

    def __init__(self, codex_home, log=print, mcp_allow=(), worker_root=None, inherit=()):
        self.account_home = str(Path(codex_home).expanduser().resolve())
        self.worker_root = worker_root
        self.inherit = tuple(_inherit_names(inherit))
        self.home = worker_home(self.account_home, worker_root, self.inherit) if worker_root else self.account_home
        self.log = log
        self.mcp_allow = set(mcp_allow)
        self.server = None
        self.lock = threading.Lock()
        self.active = {}      # thread_id -> running turn id
        self.last = {}        # thread_id -> latest finished turn: status, at, error, message
        self.activity = {}    # thread_id -> time of the last item event (progress signal)
        self.turn_started = {}
        self.thread_hosts = {}
        self.legacy = None

    def sync_auth(self):
        if self.worker_root:
            _sync_auth(self.account_home, self.home)

    def _thread_host(self, thread_id):
        """Pre-isolation lanes keep their original home; new threads stay isolated on restart."""
        if not self.worker_root:
            return self
        with self.lock:
            if thread_id not in self.thread_hosts:
                host = self
                dirs = ("sessions", "archived_sessions")
                if not any(next((Path(self.home) / d).rglob(f"*-{thread_id}.jsonl"), None) for d in dirs) \
                        and any(next((Path(self.account_home) / d).rglob(f"*-{thread_id}.jsonl"), None) for d in dirs):
                    if not self.legacy:
                        self.legacy = Headless(self.account_home, log=self.log, mcp_allow=self.mcp_allow)
                    host = self.legacy
                self.thread_hosts[thread_id] = host
            return self.thread_hosts[thread_id]

    def ensure(self):
        self.sync_auth()
        with self.lock:
            if self.server and self.server.alive:
                return self.server
            if self.worker_root:
                self.home = worker_home(self.account_home, self.worker_root, self.inherit)
            env = dict(os.environ, CODEX_HOME=self.home)
            args = ["-c", "notify=[]"]
            if self.worker_root:
                args += ["-c", 'cli_auth_credentials_store="file"']
            for name in _mcp_servers(self.home):
                if name not in self.mcp_allow:
                    args += ["-c", f"mcp_servers.{name}.enabled=false"]
            s = AppServer(args=args, client_name="mr-manager", log=self.log, env=env)
            s.listeners.append(self._notify)
            s.server_request_handler = self._server_request
            s.start()
            self.server = s
            self.active.clear()
            return s

    def _server_request(self, method, params):
        if "approval" in method.lower():
            return {"decision": "decline"}   # workers never escalate
        raise RuntimeError(f"mr-manager can't answer {method}")

    def _notify(self, method, p):
        tid = p.get("threadId")
        if not tid:
            return
        now = time.time()
        if method == "turn/started":
            self.active[tid] = p["turn"]["id"]
            self.turn_started[tid] = now
        elif method == "turn/completed":
            self.active.pop(tid, None)
            turn = p.get("turn") or {}
            self.last[tid] = dict(self.last.get(tid, {}), status=turn.get("status"), at=now,
                                  error=turn.get("error"))
            self.sync_auth()
        elif method.startswith("item/"):
            self.activity[tid] = now
            item = p.get("item") or {}
            if method == "item/completed" and item.get("type") == "agentMessage":
                self.last.setdefault(tid, {})["message"] = item.get("text", "")

    # -- the account interface (called by the daemon) ----------------------------------------
    def create(self, prompt, title, cwd, model=None, effort=None, env=None):
        s = self.ensure()
        config = {}
        if effort:
            config["model_reasoning_effort"] = effort
        if env:
            config["shell_environment_policy"] = {"inherit": "all", "set": env}
        params = {"cwd": cwd, "approvalPolicy": "never", "sandbox": "danger-full-access",
                  "threadSource": "user", "config": config or None}
        if model:
            params["model"] = model
        tid = s.request("thread/start", params)["thread"]["id"]
        self.thread_hosts[tid] = self
        try:
            s.request("thread/name/set", {"threadId": tid, "name": title})
        except RpcError:
            pass
        s.request("turn/start", {"threadId": tid, "input": [_text(prompt)]})
        self.sync_auth()
        self.activity[tid] = time.time()
        return tid

    def send(self, thread_id, text, env=None):
        """Steer a running turn (lands at its next step) or start a new one. Never queues.
        env: the lane environment, re-applied if the thread has to be resumed (e.g. after a restart)."""
        host = self._thread_host(thread_id)
        if host is not self:
            self.sync_auth()
            return host.send(thread_id, text, env=env)
        s = self.ensure()
        turn = self.active.get(thread_id)
        if turn:
            try:
                s.request("turn/steer", {"threadId": thread_id, "expectedTurnId": turn, "input": [_text(text)]})
                self.sync_auth()
                return {"steered": True}
            except RpcError:
                if thread_id in self.active:
                    raise
        try:
            s.request("turn/start", {"threadId": thread_id, "input": [_text(text)]})
        except RpcError as e:
            if "not found" not in str(e).lower() and "not loaded" not in str(e).lower():
                raise
            params = {"threadId": thread_id, "excludeTurns": True,
                      "approvalPolicy": "never", "sandbox": "danger-full-access"}
            if env:
                params["config"] = {"shell_environment_policy": {"inherit": "all", "set": env}}
            s.request("thread/resume", params)
            s.request("turn/start", {"threadId": thread_id, "input": [_text(text)]})
        self.activity[thread_id] = time.time()
        self.sync_auth()
        return {"started": True}

    def interrupt(self, thread_id):
        host = self._thread_host(thread_id)
        if host is not self:
            return host.interrupt(thread_id)
        turn = self.active.get(thread_id)
        if not turn:
            return {"interrupted": False, "reason": "no running turn"}
        self.ensure().request("turn/interrupt", {"threadId": thread_id, "turnId": turn})
        return {"interrupted": True}

    def read(self, thread_id, turns=3, outputs=False):
        host = self._thread_host(thread_id)
        if host is not self:
            return host.read(thread_id, turns=turns, outputs=outputs)
        s = self.ensure()
        r = s.request("thread/read", {"threadId": thread_id, "includeTurns": True})
        th = r.get("thread") or {}
        out = []
        for t in (th.get("turns") or [])[-turns:]:
            items = t.get("items") or []
            if not items or t.get("itemsView") == "notLoaded":
                try:
                    items = s.request("thread/items/list", {"threadId": thread_id, "turnId": t["id"]}).get("data", [])
                except RpcError:
                    items = []
            out.append({"id": t["id"], "status": t.get("status"), "items": [summarize(i, outputs) for i in items]})
        return {"thread": {"id": thread_id, "title": th.get("name") or (th.get("preview") or "")[:80],
                           "status": {"type": "active" if thread_id in self.active else "idle"},
                           "cwd": th.get("cwd")}, "turns": out}

    def last_message(self, thread_id):
        """The worker's latest message, from the thread itself (survives daemon restarts)."""
        for t in reversed(self.read(thread_id, turns=2)["turns"]):
            for it in reversed(t["items"]):
                if it["type"] == "agentMessage" and it.get("text"):
                    return t["status"], it["text"]
        return None, ""

    def status(self, thread_id):
        host = self._thread_host(thread_id)
        if host is not self:
            return host.status(thread_id)
        if self.server and not self.server.alive and thread_id in self.active:
            self.active.pop(thread_id, None)
            self.last[thread_id] = {"status": "failed", "at": time.time(),
                                    "error": "codex app-server exited; resend to resume"}
        return {"running": thread_id in self.active, "turn_started": self.turn_started.get(thread_id),
                "last_activity": self.activity.get(thread_id), **self.last.get(thread_id, {})}

    def statuses(self, thread_ids):
        return {t: self.status(t) for t in thread_ids}

    def usage(self):
        return self.ensure().request("account/rateLimits/read", {})

    def consume_reset(self):
        return self.ensure().request("account/rateLimitResetCredit/consume", {})

    def archive(self, thread_id):
        host = self._thread_host(thread_id)
        if host is not self:
            return host.archive(thread_id)
        try:
            return self.ensure().request("thread/archive", {"threadId": thread_id})
        except RpcError as e:
            return {"archived": False, "error": str(e)}


def summarize(item, outputs=False):
    t = item.get("type")
    d = {"type": t}
    if t == "userMessage":
        d["text"] = "\n".join(c.get("text", "") for c in item.get("content", []) if c.get("type") == "text")
    elif t == "agentMessage":
        d["text"] = item.get("text", "")
        d["phase"] = item.get("phase")
    elif t == "commandExecution":
        d["command"] = item.get("command")
        d["exitCode"] = item.get("exitCode")
        d["status"] = item.get("status")
        if outputs:
            d["output"] = (item.get("aggregatedOutput") or "")[-4000:]
    elif t == "fileChange":
        d["files"] = [c.get("path") for c in item.get("changes", [])]
    elif t == "webSearch":
        d["query"] = item.get("query")
    elif t in ("mcpToolCall", "dynamicToolCall"):
        d["tool"] = f"{item.get('server', '')}.{item.get('tool', '')}".strip(".")
    return d
